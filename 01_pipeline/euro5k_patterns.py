"""
Λεξικά κανόνων (regex) για την ανίχνευση Υποχρεώσεων Αναφοράς (Reporting Obligations) σε κείμενα ελληνικής νομοθεσίας, κατά το EURO-5K annotation
standard.

Τα patterns οργανώνονται στα τέσσερα στάδια του EURO-5K:
    1. DEONTIC_PATTERNS            υποχρεωτικότητα
    2. INFORMATION_PATTERNS        παροχή πληροφορίας
    3. PUBLIC_RECIPIENT_PATTERNS   αποδέκτης (δημόσια/εποπτική αρχή)
    4. SUPERVISORY_PURPOSE_PATTERNS σκοπός εποπτείας/ελέγχου
συν τους κανόνες αποκλεισμού (EXCLUSION_PATTERNS).

Όλα τα patterns γίνονται compile με re.IGNORECASE, ώστε ονόματα φορέων και ακρωνύμια (π.χ. Επιτροπή Κεφαλαιαγοράς, ΑΣΕΠ, ΓΕΜΗ) να ταιριάζουν και σε
πεζό κείμενο.
"""

import re


def compile_patterns(patterns: list[str]) -> list[re.Pattern]:
    """Compile μιας λίστας regex patterns με case-insensitive matching."""
    return [re.compile(p, re.IGNORECASE) for p in patterns]


